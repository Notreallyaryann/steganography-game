/**
 * Generates the mission cover images (with hidden messages) and the salted
 * answer hashes. Run:  npm run build:missions
 *
 * THIS FILE CONTAINS THE SOLUTIONS. Keep it out of any public deployment
 * (it is not part of the Next.js app bundle).
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { deflateSync, crc32 } from "node:zlib";
import { randomBytes } from "node:crypto";
import { embed } from "../lib/stego/lsb.ts";
import { frame } from "../lib/game/frame.ts";
import { toBase64, xorKey } from "../lib/stego/layers.ts";
import { hashAnswer } from "../lib/game/hash.server.ts";

const enc = new TextEncoder();
const W = 512, H = 384;

const DEFAULTS = { plane: 1, channels: ["r", "g", "b"], bitOrder: "msb-first", direction: "row" };

const MISSIONS = [
  {
    id: "mission-01", answer: "nighthawk", palette: [[24, 62, 98], [226, 150, 80], [240, 226, 190]],
    message: "AGENT FALCON REPORTING. THE CODEWORD IS: NIGHTHAWK",
    params: DEFAULTS, fill: 6000,
  },
  {
    id: "mission-02", answer: "copperfield", palette: [[40, 70, 52], [196, 120, 74], [232, 222, 196]],
    message: "SAFEHOUSE KEY CONFIRMED. THE CODEWORD IS: COPPERFIELD",
    params: { ...DEFAULTS, plane: 3, channels: ["g"] }, fill: 9000,
  },
  {
    id: "mission-03", answer: "marble", palette: [[70, 44, 84], [214, 96, 110], [246, 214, 170]],
    message: "THE DROP IS UNDER THE OLD BRIDGE. THE CODEWORD IS: MARBLE",
    params: { plane: 2, channels: ["r", "b"], bitOrder: "lsb-first", direction: "col" }, fill: 9000,
  },
  {
    id: "mission-04", answer: "ironclad", palette: [[20, 30, 44], [92, 140, 170], [230, 232, 220]],
    message: "THE VAULT CODE IS: IRONCLAD",
    layers: (m) => enc.encode(toBase64(xorKey(enc.encode(m), enc.encode("FALCON")))),
    params: DEFAULTS, fill: 6000,
  },
];

/** Smooth, structured cover image (so low bit planes look orderly until data is hidden). */
function cover(palette, seed) {
  const px = new Uint8ClampedArray(W * H * 4);
  const [a, b, c] = palette;
  const mix = (p, q, t) => p + (q - p) * t;
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const t = y / H;
      const wave = 0.5 + 0.5 * Math.sin(x / (40 + seed * 9) + y / 70);
      let col = [0, 1, 2].map((k) => mix(mix(a[k], b[k], t), c[k], 0.18 * wave));
      const dx = x - (W * (0.3 + 0.1 * seed)), dy = y - H * 0.32;
      const d = Math.sqrt(dx * dx + dy * dy);
      if (d < 54) col = [0, 1, 2].map((k) => mix(col[k], c[k], 0.85 - d / 80));
      if (y > H * 0.72) col = col.map((v, k) => mix(v, a[k] * 0.55, 0.65 + 0.2 * Math.sin(x / 23)));
      if (x > W * 0.58 && x < W * 0.7 && y > H * 0.5 && y < H * 0.78) col = [0, 1, 2].map((k) => a[k] * 0.45);
      const i = (y * W + x) * 4;
      px[i] = col[0]; px[i + 1] = col[1]; px[i + 2] = col[2]; px[i + 3] = 255;
    }
  }
  return px;
}

function writePng(path, px) {
  const raw = Buffer.alloc((W * 3 + 1) * H);
  for (let y = 0; y < H; y++) {
    raw[y * (W * 3 + 1)] = 0;
    for (let x = 0; x < W; x++) {
      const s = (y * W + x) * 4, d = y * (W * 3 + 1) + 1 + x * 3;
      raw[d] = px[s]; raw[d + 1] = px[s + 1]; raw[d + 2] = px[s + 2];
    }
  }
  const chunk = (type, data) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type), data]);
    const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(body) >>> 0);
    return Buffer.concat([len, body, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(H, 4); ihdr[8] = 8; ihdr[9] = 2;
  writeFileSync(path, Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0)),
  ]));
}

mkdirSync("public/assets", { recursive: true });
const answers = {};
MISSIONS.forEach((m, i) => {
  const msgBytes = m.layers ? m.layers(m.message) : enc.encode(m.message);
  const framed = frame(msgBytes);
  // random filler after the message so the hidden region is visible in the bit-plane viewer
  const payload = new Uint8Array(Math.max(framed.length, m.fill));
  payload.set(framed);
  payload.set(randomBytes(payload.length - framed.length), framed.length);

  const out = embed(cover(m.palette, i), W, H, payload, m.params);
  writePng(`public/assets/${m.id}.png`, out);

  const salt = randomBytes(8).toString("hex");
  answers[m.id] = { salt, sha256: hashAnswer(salt, m.answer) };
  console.log(`wrote public/assets/${m.id}.png`);
});

writeFileSync(
  "lib/game/answers.server.ts",
  `/** SERVER ONLY. Generated by scripts/build-missions.mjs. Salted hashes, never plaintext. */\nexport const ANSWERS: Record<string, { salt: string; sha256: string }> = ${JSON.stringify(answers, null, 2)};\n`
);
console.log("wrote lib/game/answers.server.ts");
